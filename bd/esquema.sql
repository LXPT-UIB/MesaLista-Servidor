-- ---------------------------------------------------------------------------
-- Procesos automáticos (RF-24, RP-03, RP-08)
-- ---------------------------------------------------------------------------
-- PostgreSQL no tiene eventos programados: los ejecuta php/bin/worker.php desde
-- cron (sp_mark_no_shows cada minuto y sp_daily_purge una vez al día). Reciben
-- la hora como parámetro para poder usarlos con el reloj simulado de las pruebas.

-- RF-24: toda reserva confirmada sin llegada pasa a «no presentada» al cerrarse
-- su ventana de llegada, y deja de bloquear la mesa.
-- RF-44: las pendientes de pago fuera de plazo las cancela el sistema, y su
-- solicitud de grupo pasa a «caducada». Tampoco ocupan ya la mesa.
CREATE PROCEDURE sp_mark_no_shows(p_now timestamp) LANGUAGE plpgsql AS $$
BEGIN
  UPDATE reservations
     SET status = 'no_show'
   WHERE status = 'confirmed'
     AND start_at < p_now
     AND p_now > start_at + make_interval(mins => arrival_after_min);

  UPDATE reservations
     SET status = 'cancelled', cancelled_by = 'system', cancelled_at = p_now
   WHERE status = 'pending_payment'
     AND payment_due_at < p_now;

  UPDATE group_requests g
     SET status = 'expired'
    FROM reservations r
   WHERE r.id = g.reservation_id
     AND g.status = 'accepted'
     AND r.status = 'cancelled'
     AND r.cancelled_by = 'system';
END $$;

-- Borrado diario de datos personales y limpieza de tablas auxiliares.
CREATE PROCEDURE sp_daily_purge(p_today date) LANGUAGE plpgsql AS $$
BEGIN
  -- RP-08: opciones de menú y nota, 7 días después de la fecha de la reserva.
  DELETE FROM reservation_menu_options rmo
   USING reservations r
   WHERE r.id = rmo.reservation_id
     AND r.start_at < p_today - interval '7 days';
  UPDATE reservations SET note = NULL
   WHERE note IS NOT NULL AND start_at < p_today - interval '7 days';
  UPDATE group_requests SET note = NULL
   WHERE note IS NOT NULL AND day < p_today - 7;

  -- RP-03: reservas terminadas, 90 días después de su fecha, sin datos personales.
  UPDATE reservations
     SET user_id = NULL, guest_name = NULL, guest_phone = NULL, request_id = NULL
   WHERE status IN ('completed', 'cancelled', 'no_show')
     AND start_at < p_today - interval '90 days'
     AND (user_id IS NOT NULL OR guest_name IS NOT NULL OR guest_phone IS NOT NULL);
  DELETE FROM group_requests WHERE day < p_today - 90;

  DELETE FROM sessions        WHERE expires_at < p_today;
  DELETE FROM login_attempts  WHERE created_at < p_today - interval '1 day';
  DELETE FROM link_attempts   WHERE created_at < p_today - interval '1 day';
  DELETE FROM password_resets WHERE created_at < p_today - interval '1 day';
  DELETE FROM notifications   WHERE read_at IS NOT NULL AND read_at < p_today - interval '30 days';
END $$;
