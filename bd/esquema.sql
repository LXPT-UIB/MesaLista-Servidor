-- ---------------------------------------------------------------------------
-- Reservas
-- ---------------------------------------------------------------------------
-- Estados: confirmed («confirmada»), seated («en curso»), completed
-- («completada»), cancelled («cancelada»), no_show («no presentada») y
-- pending_payment («pendiente de pago»: grupo aceptado que aún no ha pagado
-- la señal, RF-44). Solo confirmed, seated y pending_payment bloquean la mesa;
-- la última, hasta payment_due_at. Si no se paga, el sistema la cancela.
--
-- Origen: app (cliente con cuenta), local (reserva presencial con ticket) y
-- walkin (cliente sin reserva sentado por el personal, nace «en curso»).
--
-- La ventana de llegada, el plazo de cambios y la duración (start_at/end_at)
-- se copian de los parámetros al crear la reserva: un cambio de parámetros
-- solo afecta a las reservas nuevas (regla 9).
--
-- block_start es el inicio del intervalo que bloquea la mesa: el inicio de la
-- reserva o, si el cliente se sentó antes (RF-23), la hora de llegada.
CREATE TABLE reservations (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source             varchar(6)   NOT NULL CHECK (source IN ('app', 'local', 'walkin')),
  user_id            integer      NULL REFERENCES users (id) ON DELETE SET NULL,
  request_id         varchar(36)  NULL,
  code               char(10)     NULL,
  guest_name         varchar(80)  NULL,
  guest_phone        varchar(20)  NULL,
  table_id           integer      NOT NULL REFERENCES dining_tables (id),
  party_size         smallint     NOT NULL,
  start_at           timestamp(0) NOT NULL,
  end_at             timestamp(0) NOT NULL,
  arrived_at         timestamp(0) NULL,
  block_start        timestamp(0) GENERATED ALWAYS AS (LEAST(start_at, COALESCE(arrived_at, start_at))) STORED,
  status             varchar(15)  NOT NULL CHECK (status IN ('confirmed', 'seated', 'completed',
                                                             'cancelled', 'no_show', 'pending_payment')),
  arrival_before_min smallint     NOT NULL,
  arrival_after_min  smallint     NOT NULL,
  change_deadline_h  smallint     NOT NULL,
  note               varchar(200) NULL,
  consent_at         timestamp(0) NULL,
  qr_version         integer      NOT NULL DEFAULT 1,
  cancelled_by       varchar(10)  NULL CHECK (cancelled_by IN ('holder', 'restaurant', 'system')),
  cancelled_at       timestamp(0) NULL,
  payment_due_at     timestamp(0) NULL,
  deposit_cents      integer      NULL CHECK (deposit_cents >= 0),
  completed_at       timestamp(0) NULL,
  created_by         integer      NULL REFERENCES users (id) ON DELETE SET NULL,
  created_at         timestamp(0) NOT NULL,
  updated_at         timestamp(6) NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT uq_res_request UNIQUE (user_id, request_id),
  CONSTRAINT uq_res_code UNIQUE (code),
  CONSTRAINT ck_res_interval CHECK (start_at < end_at),
  CONSTRAINT ck_res_party CHECK (party_size >= 1)
);
CREATE INDEX ix_res_table_block  ON reservations (table_id, status, end_at, block_start);
CREATE INDEX ix_res_status_start ON reservations (status, start_at);
CREATE INDEX ix_res_start        ON reservations (start_at);
CREATE INDEX ix_res_user         ON reservations (user_id, status, start_at);
CREATE INDEX ix_res_updated      ON reservations (updated_at);
CREATE TRIGGER reservations_updated BEFORE UPDATE ON reservations
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Mesas unidas: mesas adicionales que el personal junta a una reserva para un
-- grupo grande. La mesa principal sigue en reservations.table_id.
CREATE TABLE reservation_tables (
  reservation_id integer NOT NULL REFERENCES reservations (id) ON DELETE CASCADE,
  table_id       integer NOT NULL REFERENCES dining_tables (id),
  PRIMARY KEY (reservation_id, table_id)
);
CREATE INDEX ix_rt_table ON reservation_tables (table_id);

-- RF-45: bloqueo de una mesa (o de todas, con table_id NULL) durante un
-- intervalo [starts_at, ends_at) por un evento privado o una avería.
CREATE TABLE table_holds (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  table_id   integer      NULL REFERENCES dining_tables (id) ON DELETE CASCADE,
  starts_at  timestamp(0) NOT NULL,
  ends_at    timestamp(0) NOT NULL,
  reason     varchar(120) NOT NULL,
  created_by integer      NULL REFERENCES users (id) ON DELETE SET NULL,
  created_at timestamp(0) NOT NULL,
  CONSTRAINT ck_holds_interval CHECK (starts_at < ends_at)
);
CREATE INDEX ix_holds_time ON table_holds (ends_at, starts_at);

-- Qué ocupa cada mesa y cuándo: la mesa principal de cada reserva, sus mesas
-- unidas y los bloqueos (estado 'hold', sin reserva). Toda comprobación de
-- disponibilidad y de estado en sala se hace sobre esta vista.
CREATE VIEW table_blocks AS
  SELECT r.id AS reservation_id, r.table_id, r.status, r.block_start, r.end_at, r.start_at, 1 AS is_main
    FROM reservations r
  UNION ALL
  SELECT r.id, rt.table_id, r.status, r.block_start, r.end_at, r.start_at, 0
    FROM reservation_tables rt
    JOIN reservations r ON r.id = rt.reservation_id
  UNION ALL
  SELECT NULL, t.id, 'hold', h.starts_at, h.ends_at, h.starts_at, 0
    FROM table_holds h
    JOIN dining_tables t ON h.table_id IS NULL OR h.table_id = t.id;

-- ---------------------------------------------------------------------------
-- RF-09 en la propia base de datos: segunda protección contra solapamientos
-- ---------------------------------------------------------------------------
-- La API ya impide los solapamientos bloqueando las mesas con SELECT ... FOR
-- UPDATE. Además, esta tabla guarda cada mesa ocupada por una reserva que la
-- bloquea (principal y unidas) con su intervalo [block_start, end_at), y la
-- restricción de exclusión rechaza dos intervalos solapados en la misma mesa
-- aunque un error en el código los dejara pasar. Se comprueba al confirmar la
-- transacción (DEFERRABLE), así que mover reservas entre mesas dentro de una
-- misma transacción sigue funcionando. La mantienen los disparadores: el
-- código PHP no la toca.
CREATE TABLE table_occupancy (
  reservation_id integer NOT NULL REFERENCES reservations (id) ON DELETE CASCADE,
  table_id       integer NOT NULL REFERENCES dining_tables (id),
  period         tsrange NOT NULL,
  PRIMARY KEY (reservation_id, table_id),
  CONSTRAINT ex_occupancy_overlap EXCLUDE USING gist (table_id WITH =, period WITH &&)
    DEFERRABLE INITIALLY DEFERRED
);

CREATE FUNCTION sync_table_occupancy(p_reservation integer) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  DELETE FROM table_occupancy WHERE reservation_id = p_reservation;
  INSERT INTO table_occupancy (reservation_id, table_id, period)
  SELECT r.id, t.table_id, tsrange(r.block_start, r.end_at)
    FROM reservations r
    CROSS JOIN LATERAL (
      SELECT r.table_id
      UNION
      SELECT rt.table_id FROM reservation_tables rt WHERE rt.reservation_id = r.id
    ) t
   WHERE r.id = p_reservation
     AND r.status IN ('confirmed', 'seated', 'pending_payment');
END $$;

CREATE FUNCTION trg_reservations_occupancy() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM sync_table_occupancy(NEW.id);
  RETURN NULL;
END $$;

CREATE FUNCTION trg_reservation_tables_occupancy() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP <> 'DELETE' THEN
    PERFORM sync_table_occupancy(NEW.reservation_id);
  END IF;
  IF TG_OP <> 'INSERT' THEN
    PERFORM sync_table_occupancy(OLD.reservation_id);
  END IF;
  RETURN NULL;
END $$;

CREATE TRIGGER reservations_occupancy
  AFTER INSERT OR UPDATE OF table_id, status, start_at, end_at, arrived_at ON reservations
  FOR EACH ROW EXECUTE FUNCTION trg_reservations_occupancy();
CREATE TRIGGER reservation_tables_occupancy
  AFTER INSERT OR UPDATE OR DELETE ON reservation_tables
  FOR EACH ROW EXECUTE FUNCTION trg_reservation_tables_occupancy();

