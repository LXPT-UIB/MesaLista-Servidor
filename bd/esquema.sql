-- RF-44: pagos de la señal con PayPal (modo sandbox). order_id es único: un
-- pedido de PayPal no se registra ni se cobra dos veces.
CREATE TABLE payments (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id integer      NOT NULL REFERENCES reservations (id),
  provider       varchar(6)   NOT NULL CHECK (provider IN ('paypal', 'fake')),
  order_id       varchar(64)  NOT NULL,
  capture_id     varchar(64)  NULL,
  amount_cents   integer      NOT NULL CHECK (amount_cents >= 0),
  currency       char(3)      NOT NULL,
  status         varchar(15)  NOT NULL DEFAULT 'created'
                 CHECK (status IN ('created', 'captured', 'refund_pending', 'refunded', 'failed')),
  last_error     varchar(255) NULL,
  created_at     timestamp(0) NOT NULL,
  updated_at     timestamp(6) NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT uq_payments_order UNIQUE (order_id)
);
CREATE INDEX ix_payments_res ON payments (reservation_id, status);
CREATE TRIGGER payments_updated BEFORE UPDATE ON payments
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

