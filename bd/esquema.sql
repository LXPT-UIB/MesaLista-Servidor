-- MesaLista · Esquema de la base de datos (PostgreSQL 16 o superior)
--
-- Todas las fechas se guardan como timestamp sin zona en hora local de Madrid,
-- como en la versión con MariaDB: el servidor, PostgreSQL (timezone =
-- 'Europe/Madrid') y PHP trabajan en esa zona. La API las devuelve en ISO 8601
-- con su desfase (+01:00 o +02:00).
--
-- Uso: psql -d mesalista -f esquema.sql   (BORRA y crea todas las tablas)

SET client_min_messages = warning;

DROP VIEW IF EXISTS table_blocks;
DROP TABLE IF EXISTS
  table_occupancy, payments, group_requests, password_resets, table_holds,
  reservation_tables, email_outbox, notifications, reservation_menu_options,
  reservations, menu_options, settings, secrets, closed_days, service_slots,
  dining_tables, link_attempts, login_attempts, sessions, users
  CASCADE;
DROP PROCEDURE IF EXISTS sp_mark_no_shows(timestamp);
DROP PROCEDURE IF EXISTS sp_daily_purge(date);
DROP FUNCTION IF EXISTS sync_table_occupancy(integer) CASCADE;
DROP FUNCTION IF EXISTS trg_reservations_occupancy() CASCADE;
DROP FUNCTION IF EXISTS trg_reservation_tables_occupancy() CASCADE;
DROP FUNCTION IF EXISTS set_updated_at() CASCADE;

-- Índices GiST sobre enteros, para la restricción de exclusión de table_occupancy.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- Marca de cambios: el panel la consulta para saber si tiene que recargar.
CREATE FUNCTION set_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := clock_timestamp();
  RETURN NEW;
END $$;

-- ---------------------------------------------------------------------------
-- Cuentas y sesiones (RF-01 a RF-05, RF-38, RF-40, RS-02, RS-05, RS-06, RS-13)
-- ---------------------------------------------------------------------------

-- Clientes, personal y administradores. Al eliminar una cuenta de cliente la
-- fila se borra (RP-02) y sus reservas quedan sin titular. El correo se guarda
-- siempre en minúsculas.
CREATE TABLE users (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role          varchar(10)  NOT NULL CHECK (role IN ('client', 'staff', 'admin')),
  name          varchar(80)  NOT NULL,
  email         varchar(254) NOT NULL,
  phone         varchar(20)  NULL,
  password_hash varchar(255) NOT NULL,
  active        boolean      NOT NULL DEFAULT true,
  created_at    timestamp(0) NOT NULL,
  CONSTRAINT uq_users_email UNIQUE (email)
);

-- Sesiones de la web y de la app (token Bearer). Solo se guarda el hash
-- SHA-256 del token: el cliente es el único que lo tiene en claro (RS-11).
CREATE TABLE sessions (
  token_hash   char(64)     PRIMARY KEY,
  user_id      integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  kind         varchar(5)   NOT NULL CHECK (kind IN ('app', 'panel')),
  created_at   timestamp(0) NOT NULL,
  last_seen_at timestamp(0) NOT NULL,
  expires_at   timestamp(0) NOT NULL
);
CREATE INDEX ix_sessions_user ON sessions (user_id);

-- RS-06: intentos de inicio de sesión por cuenta (hash del correo) e IP.
CREATE TABLE login_attempts (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email_hash char(64)     NOT NULL,
  ip         varchar(45)  NOT NULL,
  success    boolean      NOT NULL,
  created_at timestamp(0) NOT NULL
);
CREATE INDEX ix_login_attempts ON login_attempts (email_hash, ip, created_at);

-- RS-13: intentos de vincular una reserva presencial, por cuenta.
CREATE TABLE link_attempts (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  success    boolean      NOT NULL,
  created_at timestamp(0) NOT NULL
);
CREATE INDEX ix_link_attempts ON link_attempts (user_id, created_at);

-- RF-40: enlaces de un solo uso para restablecer la contraseña (solo el hash).
CREATE TABLE password_resets (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  token_hash char(64)     NOT NULL,
  expires_at timestamp(0) NOT NULL,
  used_at    timestamp(0) NULL,
  created_at timestamp(0) NOT NULL,
  CONSTRAINT uq_resets_token UNIQUE (token_hash)
);
CREATE INDEX ix_resets_user ON password_resets (user_id, created_at);

-- ---------------------------------------------------------------------------
-- Configuración del restaurante (RF-35 a RF-37)
-- ---------------------------------------------------------------------------

CREATE TABLE dining_tables (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number       smallint     NOT NULL CHECK (number >= 0),
  zone         varchar(40)  NOT NULL,
  min_capacity smallint     NOT NULL,
  max_capacity smallint     NOT NULL,
  active       boolean      NOT NULL DEFAULT true,
  -- Mesa extra: no tiene plano y solo sirve para unirla a otras (más plazas).
  join_only    boolean      NOT NULL DEFAULT false,
  -- Mesa eliminada que aún tiene reservas antiguas: no se muestra en ningún sitio.
  deleted_at   timestamp(0) NULL,
  -- Mapa de la sala: centro de la mesa en un lienzo de 1000 × 600 de su zona.
  pos_x        smallint     NULL CHECK (pos_x >= 0),
  pos_y        smallint     NULL CHECK (pos_y >= 0),
  shape        varchar(5)   NOT NULL DEFAULT 'rect' CHECK (shape IN ('rect', 'round')),
  -- Código visible: inicial de la zona y número dentro de ella (S-1, T-1, E-1).
  -- Único entre las mesas no eliminadas.
  code_live    varchar(44)  GENERATED ALWAYS AS (
                 CASE WHEN deleted_at IS NULL THEN upper(left(zone, 1)) || '-' || number::text END
               ) STORED,
  updated_at   timestamp(6) NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT uq_tables_code UNIQUE (code_live),
  CONSTRAINT ck_tables_capacity CHECK (min_capacity >= 1 AND min_capacity <= max_capacity)
);
CREATE INDEX ix_tables_updated ON dining_tables (updated_at);
CREATE TRIGGER dining_tables_updated BEFORE UPDATE ON dining_tables
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Franjas de servicio por día de la semana (1 = lunes ... 7 = domingo, ISO-8601).
-- Las horas se guardan en minutos desde medianoche; 1440 = 00:00 del día siguiente.
CREATE TABLE service_slots (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  weekday   smallint NOT NULL,
  open_min  smallint NOT NULL,
  close_min smallint NOT NULL,
  CONSTRAINT ck_slots CHECK (weekday BETWEEN 1 AND 7 AND open_min >= 0
                             AND open_min < close_min AND close_min <= 1440)
);
CREATE INDEX ix_slots_weekday ON service_slots (weekday);

CREATE TABLE closed_days (
  day date PRIMARY KEY
);

-- Parámetros del servicio (enteros). Los valores iniciales están en datos.sql.
CREATE TABLE settings (
  name  varchar(40) PRIMARY KEY,
  value integer     NOT NULL
